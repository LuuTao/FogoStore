const normalizeAddressPart = (value: string) =>
  value.trim().replace(/\s+/g, ' ').toLocaleLowerCase('vi-VN');

export const buildFullAddress = (address?: string, ward?: string, province?: string) => {
  const parts = String(address || '').split(',').map((part) => part.trim()).filter(Boolean);
  const normalizedParts = new Set(parts.map(normalizeAddressPart));

  [ward, province].forEach((part) => {
    const cleanPart = String(part || '').trim();
    if (!cleanPart) return;
    const normalized = normalizeAddressPart(cleanPart);
    if (!normalizedParts.has(normalized)) {
      parts.push(cleanPart);
      normalizedParts.add(normalized);
    }
  });

  return parts.join(', ');
};

export const getStreetAddress = (address?: string, ward?: string, province?: string) => {
  const locationParts = new Set(
    [ward, province].map((part) => normalizeAddressPart(String(part || ''))).filter(Boolean),
  );

  return String(address || '')
    .split(',')
    .map((part) => part.trim())
    .filter((part) => part && !locationParts.has(normalizeAddressPart(part)))
    .join(', ');
};
